"""Enterprise half of the auth store (DD-013): connections, SCIM groups, secret rotation.

``EnterpriseStoreMixin`` is composed into ``AuthStore``; it owns the per-org connection
CRUD (secrets AES-GCM-encrypted at rest, see ``connection_crypto``), verified-domain
claims, secret rotation with its append-only audit trail, the SCIM bearer lookup, the
membership ``external_id`` readers/writers SCIM identity keys on, and SCIM group storage.

``ENTERPRISE_AUTH_DDL`` is the one DDL source for the four enterprise tables: the auth
store's boot DDL (``ensure_auth_core_tables``) and Alembic revision
``0026_enterprise_auth_oidc_scim`` both execute it, so the two paths cannot drift. It
matches the ``downgrade`` of ``0023_flense_park_enterprise_auth`` statement for statement.
"""

