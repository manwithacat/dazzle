    def set_connection_require_sso(
        self, connection_id: str, required: bool, *, tenant_id: str | None = None
    ) -> bool:
        """Toggle ``config["require_sso"]`` on an OIDC connection (DD-013, plan EA-2).

        When on, local sign-in (password, magic link, password reset) for the
        connection's verified domains is refused and sent to the IdP
        (``enterprise_login.sso_required_for``). OIDC-only: raises ``ValueError`` on
        another type. Pass ``tenant_id`` to fence the write to one org. Stored as a JSON
        boolean (the reader matches ``is True``); off removes the key. Returns ``True``
        if a row changed.

        Switching it **on** also revokes every existing session of a user whose email
        domain is one of the connection's *verified* domains (plan EA-6): a session
        minted by password or magic link before the flag is a credential the IdP never
        saw, and the route-side checks only refuse new sign-ins.
        """
        with self._transaction() as cur:
            config, _secrets, _tenant, conn_type = self._load_config_secrets(
                cur, connection_id, tenant_id
            )
            if config is None:
                return False
            if conn_type != "oidc":
                raise ValueError(
                    f"require_sso is OIDC-only (connection {connection_id!r} is {conn_type!r})"
                )
            if required:
                config["require_sso"] = True
            else:
                config.pop("require_sso", None)
            cur.execute(
                "UPDATE connections SET config = %s, updated_at = %s WHERE id = %s",
                (json.dumps(config), datetime.now(UTC).isoformat(), connection_id),
            )
            if required:
                self._revoke_sessions_for_verified_domains(cur, connection_id)
        return True

    @staticmethod
    def _revoke_sessions_for_verified_domains(cur: Any, connection_id: str) -> int:
        """Delete sessions of users whose email domain the connection has verified."""
        cur.execute("SELECT verified_domains FROM connections WHERE id = %s", (connection_id,))
        row = cur.fetchone()
        verified = [
            d.strip().lower() for d in json.loads((row or {}).get("verified_domains") or "[]")
        ]
        if not verified:
            return 0
        cur.execute(
            "DELETE FROM sessions WHERE user_id IN "
            "(SELECT id FROM users WHERE lower(split_part(email, '@', 2)) = ANY(%s))",
            (verified,),
        )
        return int(cur.rowcount or 0)

    def claim_verified_domain(self, connection_id: str, domain: str) -> bool:
        """Atomically claim ``domain`` as verified for ``connection_id``.

        Returns ``True`` when this connection owns the domain after the call (newly
        claimed OR already its own — idempotent), ``False`` when an active connection
        of a *different org* already verified it (one verified owner per domain, and
        the owner is the org: an org's OIDC and SCIM connections share its domains,
        plan EA-6).

        Serialized via a single advisory lock (mirrors the ``membership_events``
        pattern) so concurrent verifications can neither both claim the same domain
        (the cross-connection TOCTOU) nor lost-update a connection's domain list when
        two domains are verified for it at once — the connection's current list is
        re-read fresh inside the locked transaction, never trusting a caller snapshot.
        """
        norm = domain.strip().lower().rstrip(".")
        with self._transaction() as cur:
            cur.execute("SELECT pg_advisory_xact_lock(%s)", (CONNECTION_DOMAIN_LOCK_KEY,))
            cur.execute(
                "SELECT tenant_id, verified_domains FROM connections WHERE id = %s",
                (connection_id,),
            )
            row = cur.fetchone()
            if row is None:
                return False  # no such connection
            tenant_id = row["tenant_id"]
            current = {x.strip().lower() for x in json.loads(row.get("verified_domains") or "[]")}
            if norm in current:
                return True  # already ours (idempotent)
            # Authoritative owner scan (active connections only): another org owning the
            # domain blocks; a sibling connection of the same org shares it.
            cur.execute(
                "SELECT id, tenant_id, verified_domains FROM connections WHERE status = 'active'"
            )
            for other in cur.fetchall():
                verified = [
                    x.strip().lower() for x in json.loads(other.get("verified_domains") or "[]")
                ]
                if norm in verified and other["tenant_id"] != tenant_id:
                    return False
            # Unowned or owned by this org — append to THIS connection's fresh list.
            current = {x.strip().lower() for x in json.loads(row.get("verified_domains") or "[]")}
            cur.execute(
                "UPDATE connections SET verified_domains = %s, updated_at = %s WHERE id = %s",
                (
                    json.dumps(sorted(current | {norm})),
                    datetime.now(UTC).isoformat(),
                    connection_id,
                ),
            )
            return True

